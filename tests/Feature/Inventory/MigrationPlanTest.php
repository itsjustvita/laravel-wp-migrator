/**
 * @param  array<string, mixed>  $overrides
 */
function planTheme(array $overrides = []): ThemeInventory
{
    return new ThemeInventory(...array_merge([
        'theme' => new ThemeInfo('shop', '/themes/shop', 'Shop', '2.0'),
        'child' => null,
        'isBlockTheme' => false,
        'templates' => [new Template('index.php', 'index')],
        'templateParts' => [],
        'postTypes' => [],
        'taxonomies' => [],
        'shortcodes' => [],
        'menuLocations' => [],
        'sidebars' => [],
        'blockTypes' => [],
        'scripts' => [],
        'styles' => [],
        'features' => [],
        'warnings' => [],
    ], $overrides));
}

/**
 * @param  array<string, mixed>  $overrides
 */
function planSite(array $overrides = []): SiteFacts
{
    return new SiteFacts(...array_merge(['reachable' => true, 'siteName' => 'Shop', 'homeUrl' => 'https://shop.example'], $overrides));
}

function renderPlan(ThemeInventory $theme, ?SiteFacts $site = null): string
{
    return app(MigrationPlan::class)->render($theme, $site ?? planSite(), CarbonImmutable::parse('2026-11-14'));
}

