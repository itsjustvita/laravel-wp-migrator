    $plan = renderPlan(planTheme(), planSite(['stylesheet' => 'shop']));

    expect($plan)
        ->toStartWith("# WP migration plan\n\nGenerated by `php artisan wp:inventory` on 2026-11-14 from the theme \"Shop\" 2.0.\n")
