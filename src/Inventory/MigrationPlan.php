/**
 * Writes the migration plan: a Markdown work list of the views, routes and
 * components to build, the shortcodes and blocks that need renderers, the
 * plugins that need a replacement and the content that is not migrated.
 * Every item names what to build and where, so the list can be handed to
 * whoever builds the new frontend.
 */
class MigrationPlan
{
    private const array FEATURES = [
        'post-thumbnails' => 'Featured images are imported as `posts.featured_media_id`.',
        'title-tag' => 'WP printed the `<title>`; `<x-wp-seo>` renders it from the imported SEO title.',
        'html5' => 'WP printed HTML5 markup for forms, galleries and captions; nothing to do.',
        'custom-logo' => 'The logo is a theme setting and is not imported; add it to the layout.',
        'custom-header' => 'The header image is a theme setting and is not imported.',
        'custom-background' => 'The background is a theme setting and is not imported.',
        'menus' => 'Menus are imported; see the components above.',
        'woocommerce' => 'Shop data is not migrated.',
        'editor-styles' => 'Bring the editor styles over to the frontend CSS where they style content.',
        'wp-block-styles' => 'The block styles of WP are not included; style the `wp-block-*` classes yourself.',
        'align-wide' => 'Wide and full alignments appear as `alignwide` and `alignfull` classes in the content.',
        'responsive-embeds' => 'Make embedded players responsive in the CSS.',
    ];

    private const array NOT_CONTENT = ['attachment', 'nav_menu_item', 'revision'];

    private const array NO_ARCHIVE = ['post_format'];

    private const int EXAMPLES = 5;

    /** A namespace with at least this many unknown blocks is listed as one item. */
    private const int BLOCK_GROUP = 4;

    /** @var list<string> */
    private array $installedPlugins = [];

    private ThemeInventory $theme;

    private SiteFacts $site;

    public function __construct(
        private readonly Repository $config,
        private readonly PluginCatalog $plugins,
    ) {}

    /**
     * @param  list<string>  $installedPlugins  plugin files found in the plugins directory
     */
    public function render(ThemeInventory $theme, SiteFacts $site, ?CarbonImmutable $now = null, array $installedPlugins = []): string
    {
        $this->theme = $theme;
        $this->site = $site;
        $this->installedPlugins = $installedPlugins;

        $sections = [
            $this->intro($now ?? CarbonImmutable::now()),
            $this->overview(),
            $this->users(),
            $this->routes(),
            $this->dataWithoutPages(),
            $this->components(),
            $this->renderers(),
            $this->pluginSection(),
            $this->assets(),
            $this->features(),
            $this->unsupported(),
            $this->warnings(),
            $this->nextSteps(),
        ];

        return implode("\n\n", array_filter($sections, fn (string $section): bool => $section !== ''))."\n";
    }

    private function intro(CarbonImmutable $now): string
    {
        $theme = 'the theme '.$this->theme->theme->title();

        if ($this->theme->child !== null) {
            $theme .= ' with the child theme '.$this->theme->child->title();
        }

        $lines = [
            '# WP migration plan',
            '',
            sprintf('Generated by `php artisan wp:inventory` on %s from %s.', $now->toDateString(), $theme),
            'Work through the checklists and tick items off as you build them. Each item says what to build, where it comes from and where it goes.',
            'Running the command again only replaces this file with `--force`.',
        ];

        if (! $this->site->reachable) {
            $lines[] = '';
            $lines[] = sprintf('> The source database could not be read (%s), so content counts, plugins, shortcodes and blocks used in the content, and content that is not migrated are missing from this plan.', $this->site->error);
        }

        return implode("\n", $lines);
    }

    private function overview(): string
    {
        $lines = ['## Overview', ''];

        if ($this->site->reachable) {
            $lines[] = sprintf('- Site: %s, %s', $this->site->siteName ?: 'unnamed', $this->site->homeUrl ?: 'no home URL');
        }

        $lines[] = sprintf(
            '- Theme: %s (`%s`), a %s theme%s',
            $this->theme->theme->title(),
            $this->theme->theme->slug,
            $this->theme->isBlockTheme ? 'block' : 'classic',
            $this->theme->child === null ? '' : sprintf('; child theme %s (`%s`)', $this->theme->child->title(), $this->theme->child->slug),
        );

        $active = $this->site->stylesheet;
        $scanned = $this->theme->child->slug ?? $this->theme->theme->slug;

        if ($active !== null && $active !== '' && $active !== $scanned) {
            $lines[] = sprintf('- Warning: the site uses the theme `%s`, but `%s` was scanned.', $active, $scanned);
        }

        $parts = count(array_filter($this->theme->templates, fn (Template $template): bool => $template->kind === 'part'));
        $lines[] = sprintf('- Templates: %d, template parts: %d', count($this->theme->templates) - $parts, $parts);

        $counts = $this->contentCounts();

        if ($counts !== []) {
            $lines[] = '';
            $lines[] = '| Post type | Published | Other statuses |';
            $lines[] = '| --- | ---: | ---: |';

            foreach ($counts as $type => $statuses) {
                $published = $statuses['publish'] ?? 0;
                $lines[] = sprintf('| `%s` | %d | %d |', $type, $published, array_sum($statuses) - $published);
            }
        }

        return implode("\n", $lines);
    }

    private function routes(): string
    {
        $items = [];

        $front = $this->find('front-page') ?? $this->find('home') ?? $this->find('index');
        $items[] = sprintf('- [ ] **Front page**: route `/` with the view `resources/views/home.blade.php`%s.', $this->from($front));

        foreach ($this->postTypes() as $type) {
            if ($this->hasPages($type) && ! ($type === 'post' && $this->site->reachable && ! isset($this->site->postCounts['post']))) {
                $items[] = $this->postTypeItem($type);
            }
        }

        foreach ($this->theme->templates as $template) {
            if (in_array($template->kind, ['single', 'page'], true) && $template->detail !== null) {
                $items[] = $this->specificItem($template);
            }
        }

        foreach ($this->theme->templates as $template) {
            if ($template->kind === 'custom') {
                $items[] = $this->customTemplateItem($template);
            }
        }

        array_push($items, ...$this->archiveItems());

        $search = $this->find('search');

        if ($search !== null) {
            $items[] = sprintf('- [ ] **Search**: route `/search` with the view `resources/views/search.blade.php`, for example backed by Laravel Scout%s.', $this->from($search));
        }

        $notFound = $this->find('not-found');

        if ($notFound !== null) {
            $items[] = sprintf('- [ ] **Page not found**: the view `resources/views/errors/404.blade.php`%s.', $this->from($notFound));
        }

        if ($this->find('date') !== null) {
            $items[] = sprintf('- [ ] **Date archives**: there is no URL pattern for them, so old date URLs get no redirect; build them only if they matter%s.', $this->from($this->find('date')));
        }

        if ($this->find('attachment') !== null) {
            $items[] = '- Attachment pages need no view: their redirects lead to the files.';
        }

        $note = $this->config->get('wp-migrator.urls.resolver') === DefaultUrlResolver::class
            ? 'The routes follow the URL patterns in `config/wp-migrator.php`, which the import also uses for links in the content and for redirects. Change the patterns there before the import if you want other routes.'
            : 'A custom URL resolver is configured; build the routes it points to.';

        return "## Routes and views\n\n".implode("\n", $items)."\n\n".$note;
    }

    private function postTypeItem(string $type): string
    {
        $definition = $this->definition($type);
        $plural = Str::plural(str_replace('_', '-', $type));
        $label = $this->label($type);

        $single = $this->singleTemplate($type);
        $route = $this->postRoute($type);
        $published = $this->site->postCounts[$type]['publish'] ?? null;

        $item = sprintf(
            '- [ ] **%s** (`%s`%s): %s with the view `resources/views/%s/show.blade.php`%s.',
            $label,
            $type,
            $published === null ? '' : ', '.$published.' published',
            $route === null ? 'no URL pattern; add one to `urls.patterns`' : 'route `'.$route.'`',
            $plural,
            $this->from($single),
        );

        if ($definition?->rewriteSlug !== null && $definition->rewriteSlug !== $type && ! $this->hasConfiguredSlug($type)) {
            $item .= sprintf(' Its old URLs started with `/%s/`; check that the redirects cover them with `php artisan wp:redirects:export`, and set `urls.post_type_slugs.%s` if not.', trim($definition->rewriteSlug, '/'), $type);
        }

        $archive = $this->archiveTemplate($type, $definition);

        if ($archive !== false) {
            $item .= sprintf(
                ' Archive: route `%s` with the view `resources/views/%s/index.blade.php`%s.',
                $this->archiveRoute($route, $plural),
                $plural,
                $this->from($archive),
            );
        }

        return $item;
    }

    private function label(string $type): string
    {
        return $this->definition($type)->label ?? match ($type) {
            'post' => 'Posts',
            'page' => 'Pages',
            default => Str::headline($type),
        };
    }

    /**
     * Whether the posts of a type had pages of their own: the theme did not
     * register it as not public, and the rewrite rules lead to it.
     */
    private function hasPages(string $type): bool
    {
        if (in_array($type, ['page', 'post'], true)) {
            return true;
        }

        $definition = $this->definition($type);

        if ($definition !== null) {
            return $definition->public !== false;
        }

        return $this->site->queryVars === null || in_array($type, $this->site->queryVars, true);
    }

    private function users(): string
    {
        if (! $this->site->reachable || $this->site->administrators === []) {
            return '';
        }

        $count = count($this->site->administrators);
        $accounts = array_map(
            fn (array $user): string => sprintf('`%s` (%s)', $user['login'], $user['excluded'] ? 'excluded' : 'registered '.($user['registered'] ?? 'on an unknown date')),
            $this->site->administrators,
        );

        return "## Users\n\n".sprintf(
            '- [ ] Before the import, check the %d administrator %s: %s. A hacked site can hold an attacker\'s account, which would be imported with a working password; leave such accounts out with `users.excluded`. The site has %d %s in all.',
            $count,
            $count === 1 ? 'account' : 'accounts',
            implode(', ', $accounts),
            $this->site->userCount,
            $this->site->userCount === 1 ? 'user' : 'users',
        );
    }

    private function dataWithoutPages(): string
    {
        $items = [];

        foreach ($this->postTypes() as $type) {
            if ($this->hasPages($type)) {
                continue;
            }

            $definition = $this->definition($type);
            $total = array_sum($this->site->postCounts[$type] ?? []);

            $items[] = sprintf(
                '- [ ] **%s** (`%s`%s): %s. If it holds data rather than content, such as form entries or settings, add it to `import.excluded_post_types` before the import; such data often includes personal data. Otherwise import it, but give it no route.',
                $this->label($type),
                $type,
                $total === 0 ? '' : sprintf(', %d %s', $total, $total === 1 ? 'post' : 'posts'),
                $definition !== null
                    ? sprintf('the theme registers it as not public in `%s`, so its posts had no pages', $definition->file)
                    : 'the site had no URLs for it, so it probably holds the data of a plugin',
            );
        }

        return $items === [] ? '' : "## Data without pages\n\n".implode("\n", $items);
    }

    private function specificItem(Template $template): string
    {
        $type = $template->kind === 'page' ? 'page' : ($template->subject ?? 'post');
        $route = $this->postRoute($type);
        $path = $route === null ? null : strtr($route, ['{path}' => (string) $template->detail, '{slug}' => (string) $template->detail]);

        return sprintf(
            '- [ ] **%s "%s"**: %s gets its own view `resources/views/%s/%s.blade.php`%s.',
            $type === 'page' ? 'Page' : Str::headline($type),
            $template->detail,
            $path === null ? 'it' : 'the '.($type === 'page' ? 'page' : 'post').' at `'.$path.'`',
            Str::plural(str_replace('_', '-', $type)),
            $template->detail,
            $this->from($template),
        );
    }

    private function customTemplateItem(Template $template): string
    {
        $slug = Str::slug((string) $template->subject);
        // Classic themes store the file, block themes the template's slug.
        $stored = str_ends_with($template->path, '.html') ? pathinfo($template->path, PATHINFO_FILENAME) : $template->path;

        return sprintf(
            '- [ ] **Page template "%s"**%s: a layout `resources/views/layouts/%s.blade.php` for the posts whose `posts.template` is `%s`; %s.',
            $template->subject,
            $this->from($template, ' (', ')'),
            $slug,
            $stored,
            $this->templateUsage($this->site->pageTemplates[$stored] ?? []),
        );
    }

    /**
     * @param  list<array{title: string, type: string}>  $posts
     */
    private function templateUsage(array $posts): string
    {
        if (! $this->site->reachable) {
            return 'its use is unknown';
        }

        if ($posts === []) {
            return 'no post uses it, so you may not need it';
        }

        $types = array_count_values(array_column($posts, 'type'));
        $counts = [];

        foreach ($types as $type => $count) {
            $noun = str_replace('_', ' ', $type);
            $counts[] = $count.' '.($count === 1 ? $noun : Str::plural($noun));
        }

        $titles = array_slice(array_column($posts, 'title'), 0, self::EXAMPLES);

        return sprintf(
            'used by %s: %s%s',
            implode(' and ', $counts),
            implode(', ', $titles),
            count($posts) > count($titles) ? ', …' : '',
        );
    }

    /**
     * @return list<string>
     */
    private function archiveItems(): array
    {
        $items = [];
        $taxonomies = ['category' => 'Category', 'post_tag' => 'Tag'];

        foreach (array_keys($this->site->taxonomies) as $taxonomy) {
            $taxonomies[$taxonomy] ??= Str::headline($taxonomy);
        }

        foreach ($this->theme->taxonomies as $taxonomy) {
            $taxonomies[$taxonomy->name] = $taxonomy->label ?? Str::headline($taxonomy->name);
        }

        $patterns = $this->config->get('wp-migrator.urls.term_patterns', []);
        $patterns = is_array($patterns) ? $patterns : [];

        foreach ($taxonomies as $taxonomy => $label) {
            $specific = $this->find('term', $taxonomy);
            $builtIn = in_array($taxonomy, ['category', 'post_tag'], true);
            $pattern = $patterns[$taxonomy] ?? null;
            $pattern = is_string($pattern) ? $pattern : null;

            if (in_array($taxonomy, self::NO_ARCHIVE, true) || ! $this->needsArchive($taxonomy, $specific !== null, $pattern !== null)) {
                continue;
            }

            // A taxonomy of a plugin that had no archive URLs on the site.
            if (! $builtIn && ! $this->themeTaxonomy($taxonomy) && $this->site->queryVars !== null && ! in_array($taxonomy, $this->site->queryVars, true)) {
                continue;
            }

            $plural = match ($taxonomy) {
                'category' => 'categories',
                'post_tag' => 'tags',
                default => Str::plural(str_replace('_', '-', $taxonomy)),
            };

            $template = $specific ?? ($builtIn ? null : $this->find('term')) ?? $this->find('archive') ?? $this->find('index');

            $item = sprintf(
                '- [ ] **%s archive** (`%s`): %s`resources/views/%s/show.blade.php`%s.',
                Str::singular($label),
                $taxonomy,
                $this->routeWith($pattern),
                $plural,
                $this->from($template),
            );

            if ($pattern === null) {
                $item .= ' It has no URL pattern yet; add one to `urls.term_patterns`'.($builtIn ? ' so its old URLs get redirects.' : ' so menu items that link to it work.');
            }

            if (! $builtIn) {
                $item .= ' Old URLs of these archives get no redirects; add them to the redirects table if they matter.';
            }

            $items[] = $item;
        }

        $pattern = $this->config->get('wp-migrator.urls.author_pattern');
        $author = $this->find('author');

        if (is_string($pattern) || $author !== null) {
            $items[] = sprintf(
                '- [ ] **Author archive**: %s`resources/views/authors/show.blade.php`%s.%s',
                $this->routeWith(is_string($pattern) ? $pattern : null),
                $this->from($author ?? $this->find('archive') ?? $this->find('index')),
                is_string($pattern) ? '' : ' It has no URL pattern yet; set `urls.author_pattern` so its old URLs get redirects.',
            );
        }

        return $items;
    }

    private function themeTaxonomy(string $taxonomy): bool
    {
        foreach ($this->theme->taxonomies as $definition) {
            if ($definition->name === $taxonomy) {
                return true;
            }
        }

        return false;
    }

    private function routeWith(?string $pattern): string
    {
        return $pattern === null ? 'the view ' : 'route `'.$pattern.'` with the view ';
    }

    /**
     * Archives the new site needs: those the redirects lead to, and those
     * the theme has its own template for, unless the site has no terms.
     */
    private function needsArchive(string $taxonomy, bool $hasTemplate, bool $hasPattern): bool
    {
        if ($this->site->reachable && ($this->site->taxonomies[$taxonomy] ?? 0) === 0) {
            return false;
        }

        return $hasTemplate || $hasPattern || ! in_array($taxonomy, ['category', 'post_tag'], true);
    }

    private function components(): string
    {
        $items = [];

        foreach ($this->theme->templates as $template) {
            if ($template->kind === 'partial') {
                $name = $template->subject.($template->detail === null ? '' : '-'.$template->detail);
                $items[] = sprintf('- [ ] `<x-%s>`%s.', $name, $this->from($template));
            }
        }

        foreach ($this->theme->templates as $template) {
            if ($template->kind !== 'part') {
                continue;
            }

            $loadedBy = $this->theme->templateParts[(string) $template->subject] ?? [];
            $items[] = sprintf(
                '- [ ] `<x-%s>`%s%s.',
                basename((string) $template->subject),
                $this->from($template),
                $loadedBy === [] ? '' : ', loaded by '.$this->codeList($loadedBy),
            );
        }

        foreach ($this->theme->menuLocations as $location => $description) {
            $assigned = $this->site->menus[$location] ?? null;
            $holds = match (true) {
                ! $this->site->reachable => '',
                $assigned === null => ' No menu is assigned to it.',
                default => sprintf(' It holds "%s" with %d %s.', $assigned['menu'], $assigned['items'], $assigned['items'] === 1 ? 'item' : 'items'),
            };

            $items[] = sprintf(
                "- [ ] Menu location `%s` (%s): render the menu from `Menu::whereJsonContains('locations', '%s')->first()`.%s",
                $location,
                $description,
                $location,
                $holds,
            );
        }

        foreach ($this->theme->sidebars as $sidebar) {
            $widgets = $this->site->widgets[$sidebar->id] ?? null;

            $items[] = sprintf(
                '- [ ] Sidebar "%s" (`%s`)%s, which are not migrated; rebuild what the new site needs as a component.',
                $sidebar->name,
                $sidebar->id,
                $widgets === null ? ': its widgets' : sprintf(' held %d %s', $widgets, $widgets === 1 ? 'widget' : 'widgets'),
            );
        }

        if ($items === []) {
            return '';
        }

        $intro = $this->theme->menuLocations === [] ? '' : "The models are in the namespace `ItsJustVita\\WpMigrator\\Models`.\n\n";

        return "## Components\n\n".$intro.implode("\n", $items);
    }

    private function renderers(): string
    {
        $items = [];
        $themeTags = [];

        foreach ($this->theme->shortcodes as $shortcode) {
            $themeTags[$shortcode->tag] = true;
            $items[] = sprintf(
                '- [ ] Shortcode `[%s]`, registered in `%s` with %s: %s %s, then import again with `--force`.',
                $shortcode->tag,
                $shortcode->file,
                str_starts_with($shortcode->callback, 'a ') ? $shortcode->callback : 'the callback `'.$shortcode->callback.'`',
                $this->usage($this->site->shortcodes[$shortcode->tag] ?? null),
                $this->handlerAdvice($shortcode->tag),
            );
        }

        foreach ($this->site->shortcodes as $tag => $usage) {
            if (! isset($themeTags[$tag])) {
                $items[] = sprintf(
                    '- [ ] Shortcode `[%s]`: %s It does not come from the theme, probably from a plugin. %s, or remove it from the content.',
                    $tag,
                    $this->usage($usage),
                    $this->handlerAdvice($tag),
                );
            }
        }

        $themeBlocks = [];

        foreach ($this->theme->blockTypes as $block) {
            $themeBlocks[$block->name] = true;
            $items[] = sprintf(
                '- [ ] Block `%s`, registered in `%s`: %s Create the view `%s`.',
                $block->name,
                $block->file,
                $this->usage($this->site->blocks[$block->name] ?? null),
                $this->blockView($block->name),
            );
        }

        $byNamespace = [];

        foreach ($this->site->blocks as $name => $usage) {
            if (! isset($themeBlocks[$name])) {
                $byNamespace[str_contains($name, '/') ? explode('/', $name)[0] : $name][$name] = $usage;
            }
        }

        foreach ($byNamespace as $namespace => $blocks) {
            if ($namespace !== 'core' && count($blocks) >= self::BLOCK_GROUP) {
                $items[] = $this->blockGroupItem($namespace, $blocks);

                continue;
            }

            foreach ($blocks as $name => $usage) {
                $items[] = sprintf('- [ ] Block `%s`: %s Create the view `%s`, or it renders its stored HTML.', $name, $this->usage($usage), $this->blockView($name));
            }
        }

        if ($items === []) {
            return '';
        }

        return "## Shortcodes and blocks\n\nPublish the block views first with `php artisan vendor:publish --tag=wp-migrator-views`.\n\n".implode("\n", $items);
    }

    /**
     * @param  array<string, array{count: int, post_ids: list<int>}>  $blocks
     */
    private function blockGroupItem(string $namespace, array $blocks): string
    {
        $ids = array_values(array_unique(array_merge(...array_column($blocks, 'post_ids'))));
        sort($ids);
        $ids = array_slice($ids, 0, self::EXAMPLES);

        return sprintf(
            '- [ ] %d blocks from `%s/`, used %d times, for example in the %s with the %s %s: %s. Create a view for each in `resources/views/vendor/wp-migrator/blocks/%s/`, or they render their stored HTML.',
            count($blocks),
            $namespace,
            array_sum(array_column($blocks, 'count')),
            count($ids) === 1 ? 'post' : 'posts',
            count($ids) === 1 ? 'ID' : 'IDs',
            implode(', ', $ids),
            $this->codeList(array_map(fn (string $name): string => substr($name, strlen($namespace) + 1), array_keys($blocks))),
            $namespace,
        );
    }

    private function handlerAdvice(string $tag): string
    {
        $class = Str::studly(preg_replace('/[^A-Za-z0-9]+/', ' ', $tag) ?? $tag).'Handler';

        return sprintf(
            'Write a class `%s` that implements `ShortcodeHandler` and register it with `WpMigrator::mapShortcode(\'%s\', %s::class)`',
            $class,
            $tag,
            $class,
        );
    }

    /**
     * @param  array{count: int, post_ids: list<int>}|null  $usage
     */
    private function usage(?array $usage): string
    {
        if (! $this->site->reachable) {
            return 'its use in the content is unknown.';
        }

        if ($usage === null) {
            return 'not used in the content; you may not need it.';
        }

        return sprintf(
            'used %d %s, for example in the %s with the %s %s.',
            $usage['count'],
            $usage['count'] === 1 ? 'time' : 'times',
            count($usage['post_ids']) === 1 ? 'post' : 'posts',
            count($usage['post_ids']) === 1 ? 'ID' : 'IDs',
            implode(', ', $usage['post_ids']),
        );
    }

    private function blockView(string $name): string
    {
        $path = str_starts_with($name, 'core/') ? substr($name, 5) : $name;

        return 'resources/views/vendor/wp-migrator/blocks/'.$path.'.blade.php';
    }

    private function pluginSection(): string
    {
        if (! $this->site->reachable || $this->site->plugins === []) {
            $intro = $this->site->reachable ? 'No plugins are active.' : 'The active plugins could not be read.';

            if ($this->installedPlugins === []) {
                return "## Plugins\n\n".$intro;
            }

            return "## Plugins\n\n".$intro.' These are installed; they may have been switched off, so check which of them the site used:'."\n\n".$this->pluginList($this->installedPlugins);
        }

        return "## Plugins\n\n".$this->pluginList($this->site->plugins);
    }

    /**
     * @param  list<string>  $files
     */
    private function pluginList(array $files): string
    {
        $work = [];
        $done = [];

        foreach ($files as $file) {
            $plugin = $this->plugins->classify($file);

            if ($plugin->needsWork()) {
                $work[] = sprintf(
                    '- [ ] **%s** (`%s`), %s: %s',
                    $plugin->name,
                    $plugin->file,
                    match ($plugin->status) {
                        'replace' => 'needs a replacement',
                        'unsupported' => 'not migrated',
                        default => 'unknown',
                    },
                    $plugin->advice,
                );
            } else {
                $done[] = sprintf('- **%s**, %s: %s', $plugin->name, $plugin->status === 'handled' ? 'covered by the import' : 'not needed', $plugin->advice);
            }
        }

        return implode("\n", [...$work, ...$done]);
    }

    private function assets(): string
    {
        $items = [];

        foreach ($this->theme->scripts as $script) {
            $items[] = $this->assetItem('Script', $script, 'resources/js');
        }

        foreach ($this->theme->styles as $style) {
            $items[] = $this->assetItem('Style', $style, 'resources/css');
        }

        if ($items === []) {
            return '';
        }

        return "## Assets\n\n`{theme}` stands for the theme directory and `{stylesheet}` for the directory of the active theme, the child theme if there is one.\n\n".implode("\n", $items);
    }

    private function assetItem(string $kind, AssetDefinition $asset, string $directory): string
    {
        $needs = $asset->dependencies === [] ? '' : ', needs '.$this->codeList($asset->dependencies);

        if ($asset->source === null) {
            return sprintf('- [ ] %s `%s`, registered in `%s` without a file%s: find out what it loads.', $kind, $asset->handle, $asset->file, $needs);
        }

        if (preg_match('#^(https?:)?//#', $asset->source) === 1) {
            return sprintf('- [ ] %s `%s` from `%s`%s: load it in the layout, or bundle it.', $kind, $asset->handle, $asset->source, $needs);
        }

        return sprintf('- [ ] %s `%s` from `%s`%s: move it to `%s` and build it with Vite.', $kind, $asset->handle, $asset->source, $needs, $directory);
    }

    private function features(): string
    {
        if ($this->theme->features === []) {
            return '';
        }

        $lines = array_map(
            fn (string $feature): string => sprintf('- `%s`: %s', $feature, self::FEATURES[$feature] ?? 'Check whether the new frontend needs it.'),
            $this->theme->features,
        );

        return "## Theme features\n\n".implode("\n", $lines);
    }

    private function unsupported(): string
    {
        if (! $this->site->reachable) {
            return '';
        }

        if ($this->site->findings === []) {
            return "## Unsupported content\n\nNothing found.";
        }

        $lines = array_map(
            fn ($finding): string => sprintf('- [ ] **%s**: %s. Rebuild these by hand or leave them out.', $finding->label, $finding->summary()),
            $this->site->findings,
        );

        return "## Unsupported content\n\n".implode("\n", $lines);
    }

    private function warnings(): string
    {
        if ($this->theme->warnings === []) {
            return '';
        }

        return "## Could not be read\n\nThe scan only reads values written literally in the code. Check these by hand:\n\n".implode("\n", array_map(fn (string $warning): string => '- '.$warning, $this->theme->warnings));
    }

    private function nextSteps(): string
    {
        return implode("\n", [
            '## Next steps',
            '',
            '1. Run `php artisan wp:import --dry-run`, then `php artisan wp:import`, and read the report in `storage/logs`.',
            '2. Build the items above. Render content with `<x-wp-blocks :blocks="$post->blocks" />` and the SEO tags with `<x-wp-seo :model="$post" />`.',
            '3. After changing handlers, block views or URL patterns, run `php artisan wp:import --force` to map the content again.',
            '4. Shortly before going live, run `php artisan wp:import` once more to bring over what changed, register the redirect middleware and switch the DNS.',
        ]);
    }

    /**
     * Content post types: those of the theme, those with posts, and posts and pages.
     *
     * @return list<string>
     */
    private function postTypes(): array
    {
        $types = ['page', 'post'];

        foreach ($this->theme->postTypes as $definition) {
            $types[] = $definition->name;
        }

        foreach (array_keys($this->contentCounts()) as $type) {
            $types[] = $type;
        }

        return array_values(array_unique($types));
    }

    /**
     * @return array<string, array<string, int>>
     */
    private function contentCounts(): array
    {
        $excluded = [...self::NOT_CONTENT, ...$this->config->array('wp-migrator.import.excluded_post_types')];

        return array_filter(
            $this->site->postCounts,
            fn (string $type): bool => ! in_array($type, $excluded, true),
            ARRAY_FILTER_USE_KEY,
        );
    }

    private function definition(string $type): ?PostTypeDefinition
    {
        foreach ($this->theme->postTypes as $definition) {
            if ($definition->name === $type) {
                return $definition;
            }
        }

        return null;
    }

    private function hasConfiguredSlug(string $type): bool
    {
        $slugs = $this->config->get('wp-migrator.urls.post_type_slugs', []);

        return is_array($slugs) && isset($slugs[$type]);
    }

    private function postRoute(string $type): ?string
    {
        $patterns = $this->config->get('wp-migrator.urls.patterns', []);
        $pattern = is_array($patterns) ? ($patterns[$type] ?? $patterns['*'] ?? null) : null;

        return is_string($pattern) ? str_replace('{type}', $type, $pattern) : null;
    }

    private function archiveRoute(?string $route, string $plural): string
    {
        if ($route === null) {
            return '/'.$plural;
        }

        $prefix = (string) preg_replace('#/[^/]*\{[a-z]+\}.*$#', '', $route);

        return $prefix === '' ? '/'.$plural : $prefix;
    }

    private function singleTemplate(string $type): ?Template
    {
        foreach ($this->theme->templates as $template) {
            if ($template->kind === 'single' && $template->subject === $type && $template->detail === null) {
                return $template;
            }

            if ($type === 'page' && $template->kind === 'page' && $template->detail === null) {
                return $template;
            }
        }

        return ($type === 'page' ? null : $this->find('single', 'post')) ?? $this->find('singular') ?? $this->find('index');
    }

    private function archiveTemplate(string $type, ?PostTypeDefinition $definition): Template|false|null
    {
        if ($type === 'post') {
            return $this->find('home') ?? $this->find('index');
        }

        $specific = $this->find('archive', $type);

        if ($specific !== null) {
            return $specific;
        }

        return $definition !== null && $definition->hasArchive !== null && $definition->hasArchive !== false
            ? ($this->find('archive') ?? $this->find('index'))
            : false;
    }

    /**
     * The template of a kind for one subject, or the general one without a subject.
     */
    private function find(string $kind, ?string $subject = null): ?Template
    {
        foreach ($this->theme->templates as $template) {
            if ($template->kind === $kind && $template->detail === null && $template->subject === $subject) {
                return $template;
            }
        }

        return null;
    }

    private function from(?Template $template, string $before = ', from ', string $after = ''): string
    {
        if ($template === null) {
            return '';
        }

        return $before.'`'.$template->path.'`'.($template->source === 'child' ? ' (child theme)' : '').$after;
    }

    /**
     * @param  list<string>  $values
     */
    private function codeList(array $values): string
    {
        return implode(', ', array_map(fn (string $value): string => '`'.$value.'`', $values));
    }
}
